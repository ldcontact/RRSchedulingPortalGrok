import asyncio
from playwright.async_api import async_playwright, expect
B='http://localhost:3417'; OUT='/workspace/rr-scheduler/screenshots/'
errors=[]; results=[]
def ok(label, cond):
    results.append(('PASS' if cond else 'FAIL', label)); print(('PASS ' if cond else 'FAIL ')+label)
def hook(pg, tag):
    pg.on('console', lambda m: errors.append((tag, m.type, m.text)) if m.type=='error' else None)
    pg.on('pageerror', lambda e: errors.append((tag,'pageerror',str(e))))
async def login_as(pg, email):
    await pg.context.clear_cookies(); await pg.goto(B+'/login'); await pg.click(f'#demo-users button:has-text("{email}")'); await pg.wait_for_url(lambda u: '/login' not in u); await pg.wait_for_load_state('networkidle')
